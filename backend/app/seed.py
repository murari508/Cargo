def seed(reset: bool = False) -> None:
    if reset:
        Base.metadata.drop_all(bind=engine)
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        for spec in USERS:
            if db.scalar(select(User).where(User.email == spec["email"])):
                continue
            password = spec.pop("password")
            db.add(User(**spec, password_hash=hash_password(password)))
            spec["password"] = password
        db.commit()

        for spec in CARS:
            exists = db.scalar(select(Car).where(Car.brand == spec["brand"],
                                                 Car.model == spec["model"]))
            if exists:
                for key, val in spec.items():
                    setattr(exists, key, val)
                continue
            db.add(Car(**spec, status=CarStatus.available))
        db.commit()

        if db.scalar(select(Booking)) is None:
            customer = db.scalar(select(User).where(User.email == "ravi@example.com"))
            creta = db.scalar(select(Car).where(Car.model == "Creta"))
            thar = db.scalar(select(Car).where(Car.model == "Thar"))
            today = date.today()
            demo = [
                (creta, today + timedelta(days=2), today + timedelta(days=5),
                 BookingStatus.confirmed, PaymentStatus.paid),
                (thar, today - timedelta(days=12), today - timedelta(days=9),
                 BookingStatus.completed, PaymentStatus.paid),
            ]
            if customer is not None:
                for car, start, end, bstatus, pstatus in demo:
                    if car is None:
                        continue
                    q = pricing.quote(car.price_per_day, car.category, start, end)
                    db.add(Booking(
                        user_id=customer.id, car_id=car.id,
                        pickup_location=car.location, return_location=car.location,
                        pickup_date=start, return_date=end,
                        pickup_time=time(10, 0), return_time=time(18, 0),
                        rental_days=q["rental_days"], base_price=q["base_price"],
                        taxes=q["taxes"], service_fee=q["service_fee"],
                        security_deposit=q["security_deposit"], total_amount=q["total_amount"],
                        booking_status=bstatus, payment_status=pstatus,
                        booking_reference="CG" + secrets.token_hex(4).upper(),
                    ))
            db.commit()

        print("Seeded.")
        print("  admin    admin@cargo.in / CarGoAdmin1")
        print("  customer ravi@example.com / Password1")
        print(f"  cars: {db.query(Car).count()}   bookings: {db.query(Booking).count()}")
    finally:
        db.close()


